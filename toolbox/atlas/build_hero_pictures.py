"""
The pictures of the Atlas's welcome page: atlas/hero/<name>.jpg and js/atlas/data/hero.js (window.ArcanumHero), one of
which the page picks at random each time it is opened.

Each is a screenshot of the Atlas map itself (world-atlas.html, shown without its pins and buttons) at a chosen map, tile and
zoom: the dragon's bones in the Lair of Bellerogrim, the ruins of Vendigroth with the fallen statue, Kerghan's halls in the
last map, the Roseborough inn seen from outside, and Tarant from afar.

Needs Playwright with Chromium and Pillow, and the map pictures (build_map_pictures.py).   py build_hero_pictures.py
"""
import io
import json
import sys
from pathlib import Path

from PIL import Image
from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parents[2]
DATA_JS = ROOT / 'js' / 'atlas' / 'data'                   # the generated data the pages load
OUT = ROOT / 'atlas' / 'hero'
# name, map key (None = the world map), centre tile [x, y], zoom, what it shows
VIEWS = [
    ('bellerogrim', 'The Lair of Bellerogrim', [340, 280], 0.4, 'The dragon in the Lair of Bellerogrim'),
    ('vendigroth', None, [19671, 37460], 0.3, 'The ruins of Vendigroth and their fallen statue'),
    ('kerghan', 'VOID-Kerghans Castle', [657, 79], 0.4, 'Kerghan’s halls'),
    ('roseborough', None, [112015, 96857], 0.35, 'The Roseborough inn'),
    ('tarant', None, [62243, 65664], 0.06, 'Tarant from afar'),
]
HIDE = '.pins,.nav,.filters,.tip,.legend,.hud,#msg,.side,.panel{display:none!important}'


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    with sync_playwright() as p:
        browser = p.chromium.launch(args=['--allow-file-access-from-files'])
        page = browser.new_page(viewport={'width': 1200, 'height': 700})
        errors = []
        page.on('pageerror', lambda e: errors.append(str(e)))
        page.goto((ROOT / 'world-atlas.html').as_uri() + '?embed')
        page.wait_for_timeout(2500)
        page.add_style_tag(content=HIDE)
        for name, key, tile, z, _ in VIEWS:
            page.evaluate('a => postMessage({ type: "atlas-setview", map: a[0], tile: a[1], z: a[2] }, "*")', [key, tile, z])
            page.wait_for_timeout(3500)
            img = Image.open(io.BytesIO(page.screenshot())).convert('RGB')
            img.save(OUT / (name + '.jpg'), quality=82, optimize=True)
        browser.close()
    if errors:
        print('page errors:', errors)
    (DATA_JS / 'hero.js').write_text(
        '// GENERATED by toolbox/atlas/build_hero_pictures.py - re-run it rather than editing by hand.\nwindow.ArcanumHero = '
        + json.dumps([{'src': f'atlas/hero/{n}.jpg', 'alt': t} for n, _, _, _, t in VIEWS], ensure_ascii=False) + ';\n', encoding='utf-8')
    print('Wrote', len(VIEWS), 'pictures to', OUT)


if __name__ == '__main__':
    sys.exit(main())
