"""
The daily routine of the people who walk from one place to another: js/atlas/data/routines.js (window.ArcanumRoutines).

The game moves an NPC in two ways (game/ai.c: ai_waypoints_process, ai_standpoints_process):
  * a patrol: field 287 (OBJ_F_NPC_WAYPOINTS_IDX) is a list of tiles the NPC walks round in order, and back to the first one.
    Flag 0x2 of the NPC flags (field 280, ONF_WAYPOINTS_DAY) turns the patrol on by day, 0x4 (ONF_WAYPOINTS_NIGHT) at night.
  * the standpoints: fields 289 / 290 are the tile the NPC goes to and stays near by day / by night. When the hour turns
    they walk from one to the other (and lie down in a bed that stands there). Day is 6:00 - 21:00 (ai_is_day).
Where the patrol is off for the time of day, the standpoint of that time applies. An NPC is listed only when it goes somewhere:
a patrol with a flag set, or a night standpoint more than 4 tiles from the day one.
A tile is packed as y << 32 | x. Rows are keyed by the .mob's path under data/maps (data/maps-modules for the modules), the
last element of the rows of npcs.js / submaps.js / modules.js:
  routines[file] = { d: [x, y] day standpoint, n: [x, y] night standpoint, w: [[x, y], ...] patrol, pd: 1 (by day), pn: 1 (at night) }
Re-run rather than edit:  py build_routines.py
"""
import json
import math
import sys
from pathlib import Path

import arcanum_objects as ao

ROOT = Path(__file__).resolve().parents[2]
DATA_JS = ROOT / 'js' / 'atlas' / 'data'                   # the generated data the pages load
OUT_JS = DATA_JS / 'routines.js'
NPC = 16
F_FLAGS, F_WAYPOINTS, F_STAND_DAY, F_STAND_NIGHT = 280, 287, 289, 290
ONF_WAYPOINTS_DAY, ONF_WAYPOINTS_NIGHT = 0x2, 0x4


def tile(v):
    return [v & 0xFFFFFFFF, v >> 32]


def main():
    protos = {}
    for p in (ao.DATA / 'proto').rglob('*.pro'):
        o = ao.read_proto(p)
        protos[o.proto] = o
    routines, seen = {}, 0
    for root in (ao.DATA / 'maps', ao.DATA / 'maps-modules'):
        for path in sorted(root.rglob('*.mob')):
            o = ao.read_mob(path)
            if o.type != NPC or not o.tile:
                continue
            seen += 1
            e = ao.Effective(o, protos.get(o.proto))
            flags = e.int(F_FLAGS) & 0xFFFFFFFF
            wp = e[F_WAYPOINTS]
            patrol = [tile(wp[i]) for i in sorted(wp)] if wp else []
            day, night = e.int(F_STAND_DAY), e.int(F_STAND_NIGHT)
            r = {}
            if len(patrol) > 1 and flags & (ONF_WAYPOINTS_DAY | ONF_WAYPOINTS_NIGHT):
                r['w'] = patrol
                if flags & ONF_WAYPOINTS_DAY:
                    r['pd'] = 1
                if flags & ONF_WAYPOINTS_NIGHT:
                    r['pn'] = 1
            if day and night and math.dist(tile(day), tile(night)) > 4:
                r['d'], r['n'] = tile(day), tile(night)
            elif r and day:
                r['d'] = tile(day)
            if r:
                routines[path.relative_to(root).as_posix()] = r
    note = ('routines[file] = { d: day standpoint [x, y], n: night standpoint, w: patrol [[x, y], ...] (walked in order and round), '
            'pd / pn: 1 when the patrol is on by day / at night }. Day is 6:00 - 21:00. file = last element of the rows of npcs.js / submaps.js / modules.js.')
    OUT_JS.write_text('// GENERATED by toolbox/atlas/build_routines.py - re-run it rather than editing by hand.\nwindow.ArcanumRoutines = '
                      + json.dumps({'source': 'toolbox/atlas/build_routines.py', 'note': note, 'routines': routines}, separators=(',', ':')) + ';\n', encoding='utf-8')
    print(f'Wrote {OUT_JS.name}: {len(routines)} of {seen} NPCs ({OUT_JS.stat().st_size // 1024} KB); '
          f'{sum(1 for r in routines.values() if "w" in r)} patrol, {sum(1 for r in routines.values() if "n" in r)} change place at night')


if __name__ == '__main__':
    sys.exit(main())
